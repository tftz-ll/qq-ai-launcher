const { _electron: electron } = require('playwright');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const project = path.resolve(__dirname,'..');
async function main() {
  const profile = path.join(project,'.test-artifacts','ui-profile');
  await fs.mkdir(profile,{ recursive: true });
  const env = { ...process.env, QQAI_TEST_PROFILE: profile };
  delete env.ELECTRON_RUN_AS_NODE;
  const electronApp = await electron.launch({ args: ['--no-sandbox',project], env, timeout: 30000 });
  try {
    const page = await electronApp.firstWindow();
    const errors = [];
    page.on('pageerror',e => errors.push(e.message));
    await page.waitForFunction(() => document.querySelector('#guide-title').textContent !== '准备第一次相遇');
    assert.equal(await page.locator('#ai-name').inputValue(),'');
    assert.equal(await page.locator('#persona').inputValue(),'');
    await page.screenshot({ path: path.join(project,'.test-artifacts','home.png') });
    assert.equal(await page.locator('#start').isDisabled(),true);
    await page.locator('#install-path').fill(path.join(project,'.test-artifacts','自选 安装目录'));
    await page.locator('#install-path').dispatchEvent('change');
    await page.waitForFunction(() => document.querySelector('#path-meta').textContent.includes('可用'));
    await page.locator('[data-tab="settings"]').click();
    await page.locator('[data-persona="fantasy"]').click();
    assert.ok((await page.locator('#persona').inputValue()).includes('原创角色'));
    await page.locator('[data-tab="features"]').click();
    await page.locator('#trigger').selectOption('prefix');
    assert.equal(await page.locator('#prefix-field').isVisible(),true);
    await page.locator('[data-tab="settings"]').click();
    await page.locator('#model').selectOption('deepseek-v4-pro');
    await page.screenshot({ path: path.join(project,'.test-artifacts','settings.png') });
    await page.locator('[data-tab="appearance"]').click();
    const fixture = path.join(project,'.test-artifacts','custom-background.png');
    const bytes = await electronApp.evaluate(({nativeImage}) => Array.from(nativeImage.createFromBitmap(Buffer.from([212,180,235,255,180,218,235,255,235,210,225,255,210,220,240,255]),{width:2,height:2}).toPNG()));
    await fs.writeFile(fixture,Buffer.from(bytes));
    await electronApp.evaluate(({dialog},file) => { dialog.showOpenDialog = async () => ({canceled:false,filePaths:[file]}); },fixture);
    await page.locator('#upload-background').click();
    await page.waitForFunction(() => document.querySelector('#wallpaper').style.backgroundImage.includes('qqai-media://asset/'));
    await page.locator('#upload-avatar').click();
    await page.waitForFunction(() => document.querySelector('#avatar-preview').naturalWidth === 2);
    await page.locator('#accent').selectOption('ocean');
    await page.locator('#save-appearance').click();
    await page.waitForFunction(() => document.body.dataset.accent === 'ocean');
    const appearance = JSON.parse(await fs.readFile(path.join(profile,'appearance.json'),'utf8'));
    assert.equal(appearance.accent,'ocean'); assert.match(appearance.background,/^[a-f0-9]{64}\.png$/);
    await page.locator('#remove-background').click();
    await page.locator('#remove-avatar').click();
    await page.locator('#accent').selectOption('sakura'); await page.locator('#save-appearance').click();
    await page.locator('[data-tab="tools"]').click();
    const diagnostic = path.join(project,'.test-artifacts','diagnostic.json');
    await electronApp.evaluate(({ dialog },file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); },diagnostic);
    await page.locator('#export').click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已导出'));
    const report = JSON.parse(await fs.readFile(diagnostic,'utf8'));
    assert.ok(!JSON.stringify(report).includes('sk-'));
    assert.ok(!Object.hasOwn(report,'root'));
    assert.ok(!Object.hasOwn(report,'logs'));
    assert.equal(errors.length,0,errors.join('\n'));
    await page.screenshot({ path: path.join(project,'.test-artifacts','tools.png') });
    await page.locator('#guide-topic').selectOption('token');
    await page.waitForFunction(() => document.querySelector('#guide-title').textContent.includes('Token'));
    assert.ok((await page.locator('#guide-body').innerText()).includes('Ctrl + V'));
    await page.locator('[data-tab="features"]').click();
    await page.screenshot({ path: path.join(project,'.test-artifacts','features.png') });
    await page.locator('[data-tab="home"]').click();
    await page.screenshot({ path: path.join(project,'.test-artifacts','home.png') });
    console.log('UI_SMOKE_PASSED: blank character, tutorials, custom background and avatar upload, media protocol, theme persistence, trigger and diagnostic export');
  } finally { await electronApp.evaluate(({app}) => app.exit(0)).catch(() => {}); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
